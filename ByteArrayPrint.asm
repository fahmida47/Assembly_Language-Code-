.MODEL SMALL
.STACK 100h
.DATA
NEW_LINE DB 0AH,0DH,'$' 
W DB 1,2,3,4,5         
W_END DB LABEL WORD
W_SIZE EQU W_END - W
.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX
    
    ;BYTE ARRAY PRINT
    MOV CX,5
    XOR AX,AX
    LEA SI,W
    
    PRINT:
    MOV AL,[SI]
    CALL OUTDEC
    INC SI
    
    PUSH AX
    
    MOV AH,9
    LEA DX,NEW_LINE
    INT 21H 
    
    POP AX
 
    LOOP PRINT
   
MOV AH, 4CH
INT 21H
MAIN ENDP
INCLUDE INDEC.ASM
INCLUDE OUTDEC.ASM
END MAIN