.MODEL SMALL
.STACK 100H
.DATA
NEW_LINE DB 0AH,0DH,'$'
W DW 1,2,3,4,5
W_END DW LABEL WORD
W_SIZE DW W_END - W
.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX
    
    ;PRINT WORD ARRAY 
    
    MOV CX, 5    
    MOV SI, 0 
    XOR AX,AX    
PRINT_2:
    ADD AX, W[SI] 
    INC SI
    INC SI
    LOOP PRINT_2
    
    CALL OUTDEC 

END_:
MOV AH, 4CH
INT 21H
MAIN ENDP
INCLUDE INDEC.ASM
INCLUDE OUTDEC.ASM
END MAIN